// Generates public/js/net/packets.generated.js from OpenMU's packet definitions,
// the same XML files MuMain's ClientLibrary and OpenMU generate their code from.
//
// Usage: node tools/generate-packets.mjs <path to OpenMU>/src/Network/Packets

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { XMLParser } from 'fast-xml-parser';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUTPUT = path.join(HERE, '..', 'public', 'js', 'net', 'packets.generated.js');
const SOURCES = {
  ConnectServer: 'ConnectServer/ConnectServerPackets.xml',
  ClientToServer: 'ClientToServer/ClientToServerPackets.xml',
  ServerToClient: 'ServerToClient/ServerToClientPackets.xml',
  ChatServer: 'ChatServer/ChatServerPackets.xml',
};
const ARRAY_ELEMENTS = new Set(['Packet', 'Structure', 'Field', 'Enum', 'EnumValue']);

const packetsDir = process.argv[2];
if (!packetsDir || !fs.existsSync(path.join(packetsDir, SOURCES.ServerToClient))) {
  console.error('Usage: node tools/generate-packets.mjs <OpenMU>/src/Network/Packets');
  process.exit(1);
}

const parser = new XMLParser({ ignoreAttributes: true, parseTagValue: false, isArray: (name) => ARRAY_ELEMENTS.has(name) });

const hex = (value) => (value === undefined ? undefined : parseInt(String(value), 16));
const int = (value) => (value === undefined ? undefined : parseInt(String(value), 10));

function convertField(field) {
  const converted = { name: field.Name, index: int(field.Index), type: field.Type };
  if (field.Length !== undefined) converted.length = int(field.Length);
  if (field.LeftShifted !== undefined) converted.shift = int(field.LeftShifted);
  if (field.TypeName !== undefined) converted.typeName = field.TypeName;
  if (field.ItemCountField !== undefined) converted.countField = field.ItemCountField;
  if (field.DefaultValue !== undefined) converted.defaultValue = field.DefaultValue;
  return converted;
}

function convertStructures(container) {
  const structures = {};
  for (const structure of container?.Structures?.Structure ?? []) {
    structures[structure.Name] = {
      length: int(structure.Length),
      fields: (structure.Fields?.Field ?? []).map(convertField),
    };
  }
  return structures;
}

function convertPacket(packet) {
  const header = packet.HeaderType;
  return {
    name: packet.Name,
    header: header.slice(0, 2),
    hasSubCode: header.endsWith('WithSubCode'),
    code: hex(packet.Code),
    subCode: hex(packet.SubCode),
    length: int(packet.Length),
    fields: (packet.Fields?.Field ?? []).map(convertField),
    structures: convertStructures(packet),
  };
}

const output = {};
for (const [group, file] of Object.entries(SOURCES)) {
  const xml = parser.parse(fs.readFileSync(path.join(packetsDir, file), 'utf8'));
  const root = xml.PacketDefinitions;
  output[group] = {
    structures: convertStructures(root),
    packets: Object.fromEntries((root.Packets?.Packet ?? []).map((packet) => [packet.Name, convertPacket(packet)])),
  };
}

const counts = Object.entries(output).map(([group, { packets }]) => `${group}: ${Object.keys(packets).length}`).join(', ');
const banner = `// Generated by tools/generate-packets.mjs from OpenMU's packet definitions. Don't edit.\n// ${counts}\n`;
fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
fs.writeFileSync(OUTPUT, `${banner}export const PACKETS = ${JSON.stringify(output)};\n`);
console.log(`Wrote ${path.relative(process.cwd(), OUTPUT)} (${counts})`);
